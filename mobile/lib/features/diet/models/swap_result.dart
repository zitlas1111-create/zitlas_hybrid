import 'package:flutter/foundation.dart';

/// One engine-ranked swap option.
///
/// Every field is copied VERBATIM from `POST /api/diet/swap`. Nothing here
/// derives, rounds, or reformats a nutrition value — if Flutter showed a
/// number the backend didn't send, there'd be no way to tell which layer was
/// wrong. The macros and the reason are the engine's own output.
@immutable
class SwapOption {
  const SwapOption({
    required this.name,
    required this.foods,
    required this.calories,
    required this.proteinG,
    required this.carbsG,
    required this.fatG,
    required this.reason,
    required this.availability,
    required this.budgetLevel,
    this.highProtein = false,
    this.highFiber = false,
    this.qualityLabels = const [],
  });

  final String name;
  final List<String> foods;
  final int calories;
  final double proteinG;
  final double carbsG;
  final double fatG;

  /// Generated by the engine from real macros — never model prose.
  final String reason;

  /// e.g. "Commonly available in Maharashtra".
  final String availability;

  /// Economy / Standard / Premium.
  final String budgetLevel;

  /// Only true when the DATASET says so, so the UI can never overclaim.
  final bool highProtein;

  /// Same contract as [highProtein] — dataset-derived, never guessed.
  final bool highFiber;

  /// Subtle, data-backed labels beyond the two flat booleans above (e.g.
  /// "Better protein match", "Similar calories", "Transformation
  /// friendly") — see routes/swap.py's quality_labels for exactly which
  /// real numbers justify each one. Absent/empty is normal; nothing here
  /// is a health claim the backend didn't already verify against the
  /// dataset.
  final List<String> qualityLabels;

  static SwapOption? fromMap(Map<String, dynamic> m) {
    final name = m['name'];
    if (name is! String) return null;
    double d(Object? v) => (v as num?)?.toDouble() ?? 0;
    return SwapOption(
      name: name,
      foods: [for (final f in (m['foods'] as List? ?? const [])) f.toString()],
      calories: (m['calories'] as num?)?.toInt() ?? 0,
      proteinG: d(m['protein_g']),
      carbsG: d(m['carbs_g']),
      fatG: d(m['fat_g']),
      reason: m['reason'] as String? ?? '',
      availability: m['availability'] as String? ?? '',
      budgetLevel: m['budget_level'] as String? ?? '',
      highProtein: m['high_protein'] == true,
      highFiber: m['high_fiber'] == true,
      qualityLabels: [
        for (final l in (m['quality_labels'] as List? ?? const [])) l.toString(),
      ],
    );
  }
}

/// The full deterministic-swap response.
@immutable
class SwapResult {
  const SwapResult({
    required this.options,
    required this.relaxedMatch,
    required this.matchNote,
    this.elapsedMs = 0,
    this.llmUsed = false,
  });

  final List<SwapOption> options;

  /// True when the engine had to widen the nutrition band to find anything.
  /// Surfaced in the UI rather than hidden — presenting a widened result as a
  /// true nutritional peer would be dishonest.
  final bool relaxedMatch;
  final String matchNote;
  final double elapsedMs;

  /// Always false on this path. Kept so a regression back to the LLM route
  /// would be visible rather than silent.
  final bool llmUsed;

  bool get isEmpty => options.isEmpty;

  static SwapResult fromMap(Map<String, dynamic> m) {
    return SwapResult(
      options: [
        for (final o in (m['options'] as List? ?? const []))
          if (o is Map) ?SwapOption.fromMap(o.cast<String, dynamic>()),
      ],
      relaxedMatch: m['relaxed_match'] == true,
      matchNote: m['match_note'] as String? ?? '',
      elapsedMs: (m['elapsed_ms'] as num?)?.toDouble() ?? 0,
      llmUsed: m['llm_used'] == true,
    );
  }
}
